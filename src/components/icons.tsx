export type IconName = keyof typeof BRAND | keyof typeof GLYPH;

/** Decorative 16px icon; the text next to it carries the meaning. */
export function Icon({
  name,
  className,
}: {
  name: IconName;
  className?: string;
}) {
  const cls = cx("size-4 shrink-0", className);
  if (name in BRAND) {
    const b = BRAND[name as keyof typeof BRAND];
    return (
      <svg
        aria-hidden="true"
        focusable="false"
        viewBox={b.viewBox}
        className={cx(cls, "fill-current")}
      >
        <path d={b.d} />
      </svg>
    );
  }
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cls}
    >
      {GLYPH[name as keyof typeof GLYPH]}
    </svg>
  );
}

const HOSTS: [RegExp, IconName][] = [
  [/(^|\.)(youtube\.com|youtu\.be)$/, "youtube"],
  [/(^|\.)github\.com$/, "github"],
  [/(^|\.)instagram\.com$/, "instagram"],
  [/(^|\.)(discord\.com|discord\.gg)$/, "discord"],
  [/(^|\.)(notion\.site|notion\.so)$/, "notion"],
];

const BY_TYPE: Record<z.infer<typeof LinkType>, IconName> = {
  github: "github",
  demo: "globe",
  docs: "book",
  video: "play",
  slides: "slides",
  article: "article",
  store: "store",
  certificate: "award",
  other: "link",
};

/** The service the link goes to when it is a known one, else the link's type. */
export function linkIcon(
  url: string,
  type: z.infer<typeof LinkType>,
): IconName {
  if (url.startsWith("mailto:")) return "mail";
  try {
    const host = new URL(url).hostname;
    const hit = HOSTS.find(([re]) => re.test(host));
    if (hit) return hit[1];
  } catch {
    // not an absolute URL; fall back to the type
  }
  return BY_TYPE[type];
}
